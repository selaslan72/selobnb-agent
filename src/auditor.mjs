import crypto from 'node:crypto';
import { CONFIG, getActiveNetwork } from './config.mjs';
import { extractSoliditySource } from './evaluator.mjs';

const rules = [
  ['SEC-001', /\.call\s*\{|\.(?:transfer|send)\s*\(/, 'External value/transfer call', 'HIGH', 'Inspect call target, error handling and state-update ordering. This text match does not establish reentrancy.'],
  ['SEC-002', /\b(?:selfdestruct|suicide)\s*\(/, 'Destruction opcode reference', 'HIGH', 'Review authorization and opcode behavior on the target chain and fork. A reference alone does not establish exploitability.'],
  ['SEC-003', /\.delegatecall\s*\(/, 'Delegatecall reference', 'HIGH', 'Review who controls the target and whether delegated code can change sensitive storage.'],
  ['SEC-004', /\btx\.origin\b/, 'tx.origin reference', 'HIGH', 'Check whether this value participates in authorization. Other uses are not automatically vulnerabilities.'],
  ['SEC-005', /\.transfer(?:From)?\s*\(/, 'Transfer return handling to review', 'MEDIUM', 'Inspect receiver type and return-value handling; this matcher cannot distinguish Ether transfers from token calls.'],
  ['SEC-006', /\bblock\.timestamp\b|\bnow\b/, 'Timestamp reference', 'LOW', 'Review whether timestamp dependence affects randomness, deadlines or economic outcomes. Ordinary deadline checks can be appropriate.'],
  ['SEC-007', /pragma\s+solidity\s+\^/, 'Compiler version range', 'INFO', 'Check the actual pinned build compiler. A pragma range alone does not demonstrate a security defect.'],
];

export class SmartContractAuditor {
  constructor(options = {}) {
    const network = getActiveNetwork();
    this.identity = { name: CONFIG.agentName, tokenId: CONFIG.agentTokenId, providerId: CONFIG.providerAgentId, network: network.name, chainId: network.chainId, ...options.identity };
  }

  async runAudit(sourceCode, contractTitle = 'Contract') {
    if (!extractSoliditySource({ sourceCode })) throw new Error('Explicit Solidity source is required; a job brief is not source code');
    const findings = this.detectVulnerabilities(sourceCode);
    const sourceHash = crypto.createHash('sha256').update(sourceCode).digest('hex');
    const reportMarkdown = this.formatReportMarkdown({ title: contractTitle, findings, sourceHash, timestamp: new Date().toISOString() });
    return {
      title: contractTitle, screeningOnly: true, findingsCount: findings.length, findings,
      sourceHash, reportMarkdown,
      sha256Hash: crypto.createHash('sha256').update(reportMarkdown).digest('hex'),
    };
  }

  detectVulnerabilities(code) {
    // Preserve line numbering while ignoring comments; this is deliberately not a Solidity parser.
    const screened = code.replace(/\/\*[\s\S]*?\*\/|\/\/[^\n]*/g, comment => comment.replace(/[^\n]/g, ' '));
    const lines = screened.split('\n');
    return rules.flatMap(([id, pattern, title, severity, description]) => {
      const matchedLines = lines.flatMap((line, index) => pattern.test(line) ? [index + 1] : []);
      return matchedLines.length ? [{ id, title, severity, description, lines: matchedLines, validation: 'Unvalidated pattern signal' }] : [];
    });
  }

  formatReportMarkdown({ title, findings, sourceHash, timestamp }) {
    return `# Solidity Source Pre-Screen: ${String(title).replace(/[\r\n]/g, ' ')}

**Agent:** ${this.identity.name} · Token: ${this.identity.tokenId || 'not configured'} · Provider: ${this.identity.providerId || 'not configured'}
**Date:** ${new Date(timestamp).toUTCString()}
**Network:** ${this.identity.network} (chain ${this.identity.chainId})
**Source SHA-256:** ${sourceHash}
**Scope:** Automated text-pattern pre-screening only. Findings are unvalidated signals for human review, not confirmed vulnerabilities.
**Limits:** No semantic analysis, compilation, formal verification, exploit testing, full audit, PDF, code diffs or security certification. No security pass/fail verdict is issued. Comments are ignored heuristically; string contents and unusual formatting can still cause false positives or missed signals.
**Integrity:** SHA-256 identifies report bytes. It does not prove correctness or contract safety.

## Pattern signals (${findings.length})

${findings.length === 0 ? '*No configured patterns matched. This does not establish that the contract is safe.*' : findings.map(f => `### [${f.id}] ${f.title}
* **Triage priority:** ${f.severity}
* **Evidence lines:** ${f.lines.join(', ')}
* **Validation:** ${f.validation}
* **Suggested review:** ${f.description}
`).join('\n')}

## Report provenance
Generated by **${this.identity.name}** for ${this.identity.network} (chain ${this.identity.chainId}).
No on-chain delivery or settlement is asserted by this report generator.
`;
  }
}
